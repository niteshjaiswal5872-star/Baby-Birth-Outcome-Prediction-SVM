import numpy as np 
import pandas as pd 
import streamlit as st
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC 
from sklearn.metrics import accuracy_score 
df=pd.read_csv("baby.csv")
st.title("Baby Birth Survival Prediction")
print(df.head())
num_columns=["Mother_Age","Gestational_Weeks","Maternal_BMI","Systolic_Blood_Pressure","Hemoglobin","Blood_Sugar","Prenatal_Visits","Exercise_Hours_Per_Week"]
cat_columns=["Smoking","Alcohol_Use","Previous_Complications","Stress_Level"]
for i in num_columns:
    df[i]=df[i].fillna(df[i].mean())
for i in cat_columns:
    df[i]=df[i].fillna(df[i].mode()[0]) 
df=pd.get_dummies(df,columns=cat_columns,drop_first=True)
x=df.drop("Birth_Outcome",axis=1)
y=df["Birth_Outcome"]
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42,stratify=y)
scaler=StandardScaler()
xtrain_scaled=scaler.fit_transform(x_train)
xtest_scaled=scaler.transform(x_test)   
model = SVC(class_weight={"Normal": 1, "At_Risk": 1.5})
model.fit(xtrain_scaled,y_train)
y_pred=model.predict(xtest_scaled)    
accuracy=accuracy_score(y_test,y_pred)
st.write("Machine Learning Project Using SVM model")
st.subheader("Model Performance:")
st.write("SVM Accuracy: ",round(accuracy*100,2),"%")
st.write("Enter the information of the patient: ")
age=st.slider("Mother Age",18,60,25)
gestation_week=st.slider("Gestation Weeks",20,45,38)
bmi=st.number_input("Bmi",10,40,20)
blood_pressure=st.slider("Systolic Blood Pressiure",60,200,80)
haemoglobin=st.number_input("Haemoglobin",2,20,8)
sugar=st.slider("Blood Sugar",30,250,90)
prenatal_visit=st.number_input("Parental Visits",0,10,4)
exercise=st.number_input("Exercise Hours Per Week",1,8,2)
smoking=st.selectbox("Smoking",["Yes","No"])
alcohol=st.selectbox("Are you using Alcohol?",["Yes","No"])
complications=st.selectbox("Is there any Previous complications?",["Yes","No"])
stress=st.selectbox("Hpw much you are Stressed",["high","medium","low"])
input=pd.DataFrame({"Mother_Age":age,
                    "Gestational_Weeks":[gestation_week],
                    "Maternal_BMI":[bmi],
                    "Systolic_Blood_Pressure":[blood_pressure],
                    "Hemoglobin":[haemoglobin],
                    "Blood_Sugar":[sugar],
                    "Prenatal_Visits":[prenatal_visit],
                    "Exercise_Hours_Per_week":[exercise],
                    "Smoking":[smoking],
                    "Alcohol_Use":[alcohol],
                    "Previous_Complications":[complications],
                    "Stress_Level":[stress]})
input_data=pd.get_dummies(input,columns=cat_columns,drop_first=True)
input_data = input_data.reindex(columns=x.columns,fill_value=0)
input_scaled=scaler.transform(input_data)
if st.button("Predict Birth Outcome:"):
    prediction=model.predict(input_scaled)[0]
    st.subheader("Prediction: ")
    if prediction=="Normal":
        st.success("Predicted Outcome: Normal")
    else:
        st.warning("Predicted Outcome: At Risk")    
    st.info(
        "This prediction is generated by an educational machine learning model "
        "and is not a medical diagnosis."
    )    
y_pred = model.predict(xtest_scaled)
print(pd.Series(y_pred).value_counts())    
from sklearn.metrics import classification_report

print(classification_report(y_test, y_pred))
    